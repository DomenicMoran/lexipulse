/**
 * Bundles pdf.js plus the bridge into one self-contained HTML asset.
 *
 * The output is committed, so a build never needs pdfjs-dist or a network. It also has to
 * be self-contained for a second reason: a page loaded from `file://` cannot `import`
 * sibling modules — Chromium blocks that as a cross-origin request — so everything has to
 * live in a single classic <script>.
 *
 *   node scripts/build-pdf-bridge.mjs
 */
import { build } from 'esbuild';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, '..');
const require = createRequire(import.meta.url);
const pdfjsVersion = JSON.parse(
  readFileSync(require.resolve('pdfjs-dist/package.json'), 'utf8'),
).version;

const result = await build({
  entryPoints: [resolve(here, 'pdf-bridge-entry.js')],
  bundle: true,
  format: 'iife',
  // Android WebView and WKWebView are both evergreen Chromium/WebKit, but the legacy
  // pdf.js build already targets older syntax; matching it keeps the output uniform.
  target: ['chrome90', 'safari15'],
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
});

const js = result.outputFiles[0].text;

// A literal `</script>` anywhere in the bundle would end the tag early. Splitting the
// sequence is the standard, behaviour-preserving fix.
const safe = js.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>LexiPulse PDF bridge</title>
<!-- Generated by scripts/build-pdf-bridge.mjs. pdfjs-dist ${pdfjsVersion}. Do not edit. -->
</head>
<body>
<script>${safe}</script>
</body>
</html>
`;

const outDir = resolve(projectRoot, 'assets', 'pdfjs');
mkdirSync(outDir, { recursive: true });
const outFile = resolve(outDir, 'pdf-bridge.html');
writeFileSync(outFile, html, 'utf8');

process.stdout.write(
  `wrote assets/pdfjs/pdf-bridge.html — ${(html.length / 1024).toFixed(0)} KB, pdfjs-dist ${pdfjsVersion}\n`,
);
